def decode_token(token: str) -> dict[str, Any]:
    """Decode and validate a JWT token, returning its payload."""
    return cast(dict[str, Any], jwt.decode(token, settings.SECRET_KEY, algorithms=[settings.ALGORITHM]))


def token_payload(token: str) -> dict[str, Any] | None:
    """Decode a JWT token without raising on error; returns None if invalid."""
    try:
        return decode_token(token)
    except JWTError:
        return None
